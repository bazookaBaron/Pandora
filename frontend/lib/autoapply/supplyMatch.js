function yearMonth(v) {
  const s = String(v || "");
  const m = s.match(/(19|20)\d{2}/);
  if (!m) return null;
  const mm = s.match(/(19|20)\d{2}-(\d{1,2})/);
  return [Number(m[0]), mm ? Number(mm[2]) : 6];
}

