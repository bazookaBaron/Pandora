function clean(s) {
  let out = String(s || "").toLowerCase();
  for (const [rx, rep] of PHRASES) out = out.replace(rx, rep);
  return out;
}

export function tokens(s, expandAmbiguous = true) {
  const out = [];
  for (const raw of clean(s).match(WORD) || []) {
    const w = stripDots(raw);
    if (!w || STOP.has(w)) continue;
    if (AMBIGUOUS.has(w) && !expandAmbiguous) {
      out.push(w);
      continue;
    }
    out.push(...(WANTED_ONLY[w] || SYN[w] || w).split(/\s+/));
  }
  return out;
}

function postingTokens(title, expandPm) {
  const raw = clean(String(title || "").toLowerCase().replace(/(?<=[a-z])[-_](?=\d)/g, " "));
  const timeCtx = TIME_CTX.test(raw);
  const words = (raw.match(WORD) || []).map(stripDots);
  const out = [];
  words.forEach((w, i) => {
    if (!w || STOP.has(w)) return;
    if ((w === "pm" || w === "am") && (timeCtx || (i && isDigits(words[i - 1])))) return;
    if (w === "soc" && i + 1 < words.length && isDigits(words[i + 1])) return;
    if (w === "pm" && expandPm) out.push("product", "manager");
    else if (AMBIGUOUS.has(w)) out.push(w);
    else out.push(...(SYN[w] || w).split(/\s+/));
  });
  return out;
}

function ordered(w, t) {
  const go = (wi, pos) => {
    if (wi === w.length - 1) return true;
    for (const nxt of [pos + 1, pos + 2]) {
      if (nxt >= t.length || t[nxt] !== w[wi + 1]) continue;
      if (nxt === pos + 2 && BLOCK_FILLER.has(t[pos + 1]) && t[pos + 1] !== w[wi + 1]) continue;
      if (go(wi + 1, nxt)) return true;
    }
    return false;
  };
  return t.some((x, i) => x === w[0] && go(0, i));
}

function domainMatch(w, t, wanted) {
  let dom = w.filter((x) => !ROLE_NOUNS.has(x) && !FUNCTION_NOUNS.has(x));
  if (!dom.length) dom = w;
  const ts = new Set(t);
  if (!dom.every((x) => ts.has(x)) || ![...ts].some((x) => FUNCTION_NOUNS.has(x))) return false;
  if ([...ts].some((x) => SALESY.has(x) && !wanted.has(x))) return false;
  for (const [a, b] of SALESY_BIGRAMS) {
    if (wanted.has(a) && wanted.has(b)) continue;
    for (let i = 0; i < t.length - 1; i++) if (t[i] === a && t[i + 1] === b) return false;
  }
  return true;
}

export function titleMatch(title, wanted) {
  const variants = [
    [tokens(wanted), postingTokens(title, true)],
    [tokens(wanted, false), postingTokens(title, false)],
  ];
  for (const [w, t] of variants) {
    if (!w.length) continue;
    if (w.some((x) => DOMAIN_TERMS.has(x))) {
      if (domainMatch(w, t, new Set(w))) return true;
    } else if (ordered(w, t)) return true;
  }
  return false;
}

const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function hardExcluded(title, hard) {
  const t = " " + String(title || "").toLowerCase().replace(/\s+/g, " ") + " ";
  return (hard || []).some((x) => new RegExp(`(?<![a-z0-9])${escRe(String(x).toLowerCase())}(?![a-z0-9])`).test(t));
}

